#!/bin/bash
# Install or update Restore Probe (Debian/Raspberry Pi OS, run as root).
#
#   sudo ./scripts/install.sh                     install/update from this directory
#   sudo ./scripts/install.sh --nginx             also install the nginx site for the report (port 8096)
#   sudo ./scripts/install.sh --prometheus-admin-api
#                                                 add --web.enable-admin-api to /etc/default/prometheus (with backup)
#   sudo ./scripts/install.sh --ha-setup          create input_datetime + dead-man's-switch automation in Home Assistant
#
# Idempotent: running it again is harmless. An existing config.yaml/.env is never overwritten.
set -euo pipefail

APP=/opt/restore-probe/app
VENV=/opt/restore-probe/venv
ETC=/etc/restore-probe
STATE=/var/lib/restore-probe
SRC="$(cd "$(dirname "$0")/.." && pwd)"
NGINX=0; PROM=0; HASETUP=0
for a in "$@"; do
  case "$a" in
    --nginx) NGINX=1 ;;
    --prometheus-admin-api) PROM=1 ;;
    --ha-setup) HASETUP=1 ;;
    *) echo "Unknown option: $a"; exit 2 ;;
  esac
done
[[ $EUID -eq 0 ]] || { echo "Please run as root (sudo)."; exit 1; }

log() { printf '\e[1;34m==>\e[0m %s\n' "$*"; }

log "Packages"
export DEBIAN_FRONTEND=noninteractive
apt-get install -y -q python3-venv python3-pip restic sqlite3 rsync iptables >/dev/null
command -v docker >/dev/null || { echo "Docker is missing – install it first."; exit 1; }

log "Program files → $APP"
mkdir -p "$APP" "$ETC" "$STATE" /var/log/restore-probe
rsync -a --delete --exclude .git --exclude '__pycache__' --exclude '.pytest_cache' --exclude '.venv' "$SRC/" "$APP/"
chmod 755 "$APP"/scripts/*.sh

log "Python environment $VENV"
[[ -x $VENV/bin/python ]] || python3 -m venv "$VENV"
"$VENV/bin/pip" install -q --upgrade pip >/dev/null
"$VENV/bin/pip" install -q "$APP" >/dev/null
ln -sf "$VENV/bin/restore-probe" /usr/local/bin/restore-probe

log "Configuration in $ETC"
[[ -f $ETC/config.yaml ]] || install -m 644 "$APP/config/config.example.yaml" "$ETC/config.yaml"
[[ -f $ETC/.env ]] || install -m 600 "$APP/config/env.example" "$ETC/.env"
chmod 600 "$ETC/.env"; chown root:root "$ETC/.env"
[[ -f $ETC/service.env ]] || cat > "$ETC/service.env" <<EOF
# Environment for the systemd units (no secrets here)
RESTORE_PROBE_REPORT_URL=http://$(hostname -I | awk '{print $1}'):8096/
EOF

log "systemd units"
install -m 644 "$APP"/systemd/*.service "$APP"/systemd/*.timer /etc/systemd/system/
install -m 644 "$APP/config/logrotate" /etc/logrotate.d/restore-probe
# Host-specific write paths for the backup unit, derived from config.yaml
mkdir -p /etc/systemd/system/restic-backup.service.d
EXTRA="$("$VENV/bin/python" "$APP/scripts/systemd_paths.py" "$ETC/config.yaml" 2>/dev/null || true)"
cat > /etc/systemd/system/restic-backup.service.d/paths.conf <<EOF
# Generated by install.sh from $ETC/config.yaml – re-run install.sh after changing backup paths
[Service]
ReadWritePaths=$EXTRA
EOF
systemctl daemon-reload
systemctl enable --now restore-probe.timer restic-backup.timer >/dev/null

log "Sandbox image for the isolation test"
docker pull -q alpine:3.20 >/dev/null || echo "   (docker pull alpine:3.20 failed – retry later)"

if [[ $NGINX -eq 1 ]] && [[ -d /etc/nginx/sites-available ]]; then
  log "nginx site restore-probe (port 8096)"
  install -m 644 "$APP/config/nginx-site.conf" /etc/nginx/sites-available/restore-probe
  ln -sf /etc/nginx/sites-available/restore-probe /etc/nginx/sites-enabled/restore-probe
  mkdir -p "$STATE/www"; chmod 755 "$STATE" "$STATE/www"
  "$VENV/bin/restore-probe" report >/dev/null 2>&1 || true
  nginx -t && systemctl reload nginx
fi

if [[ $PROM -eq 1 ]]; then
  F=/etc/default/prometheus
  if grep -q -- '--web.enable-admin-api' "$F"; then
    log "Prometheus: admin API already enabled"
  else
    log "Prometheus: enabling --web.enable-admin-api (backup: $F.bak-$(date +%Y%m%d))"
    cp -a "$F" "$F.bak-$(date +%Y%m%d)"
    sed -i -E 's/^ARGS="(.*)"$/ARGS="\1 --web.enable-admin-api"/' "$F"
    systemctl restart prometheus
    sleep 3; systemctl is-active prometheus >/dev/null && echo "   Prometheus is running again"
  fi
fi

if [[ $HASETUP -eq 1 ]]; then
  log "Home Assistant: input_datetime and dead-man's-switch automation"
  "$VENV/bin/python" "$APP/scripts/ha_setup.py"
fi

echo
log "Done. Next steps:"
echo "   1. Enter the secrets:        sudoedit $ETC/.env      (HA_TOKEN, HA_BACKUP_KEY, RESTIC_PASSWORD) – see README → Secrets"
echo "   2. Check the configuration:  sudo restore-probe check-config"
echo "   3. Prove the isolation:      sudo restore-probe selftest"
echo "   4. First backup:             sudo systemctl start restic-backup.service"
echo "   5. First run:                sudo systemctl start restore-probe.service   (or: sudo restore-probe run --only grafana)"
echo "   Timers: $(systemctl list-timers restore-probe.timer restic-backup.timer --no-pager | sed -n '2,3p' | awk '{print $1" "$2" "$3" "$4}' | tr '\n' ';')"
